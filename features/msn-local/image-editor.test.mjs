import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import sharp from 'sharp';
import { imageLibrary } from './images.mjs';
import { createProjectStore } from './projects.mjs';
import { assignLayerAsset } from './assign-layer.mjs';

test('an edit keeps the original, stamps only the new image, and returns to one layer', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'plexa-edit-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const lib = imageLibrary(root, root);
  const bytes = await sharp({ create: { width: 40, height: 30, channels: 3, background: '#3366cc' } }).png().toBuffer();
  const original = await lib.upload(bytes, 'Player photo', 'https://example.com/story');
  const originalFile = await fs.readFile(lib.file(original));
  const before = (await lib.list()).length;
  await assert.rejects(lib.edit({ id: original.id }), /Change the image/);
  assert.equal((await lib.list()).length, before);
  await assert.rejects(lib.edit({ id: original.id, crop: { left: 0, top: 0, width: 80, height: 10 } }), /Crop must fit/);
  assert.deepEqual(await fs.readFile(lib.file(original)), originalFile);
  assert.equal((await lib.list()).length, before);
  const previewBefore = (await lib.list()).map(item => item.updatedAt);
  const preview = await lib.preview({ id: original.id, brightness: 20 });
  assert.ok(preview.length > 20);
  assert.deepEqual((await lib.list()).map(item => item.updatedAt), previewBefore);
  const edited = await lib.edit({ id: original.id, crop: { left: 5, top: 4, width: 20, height: 10 }, rotate: 0, brightness: 10 });
  assert.equal(edited.kind, 'edited');
  assert.equal(edited.parentId, original.id);
  assert.equal(edited.width, 20);
  assert.equal(edited.height, 10);
  assert.equal(edited.sourceAsset, 'images/' + original.id + '.png');
  assert.equal(new Date(edited.updatedAt).toISOString(), edited.updatedAt);
  assert.notEqual(edited.updatedAt, original.updatedAt);
  assert.equal((await lib.get(original.id)).updatedAt, original.updatedAt);
  assert.deepEqual(await fs.readFile(lib.file(original)), originalFile);
  const cutout = { ...original, id: 'aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee', kind: 'cutout', parentId: original.id, name: 'Player photo · cutout' };
  await fs.writeFile(path.join(root, 'images', 'catalogue.json'), JSON.stringify([original, edited, cutout], null, 2));
  await assert.rejects(imageLibrary(root, root).edit({ id: cutout.id, brightness: 5 }), /Cutouts stay in the Library/);
  const store = createProjectStore(path.join(root, 'studio'));
  const project = await store.create('transfer', { title: 'TEAMtalk transfer' });
  const scene = project.scenes[0];
  const layer = scene.layers.find(item => item.type === 'image');
  const saved = await assignLayerAsset(store, { projectId: project.id, sceneId: scene.id, layerId: layer.id, asset: 'images/' + edited.id + '.png' });
  assert.equal(saved.scenes[0].layers.find(item => item.id === layer.id).asset, 'images/' + edited.id + '.png');
  assert.notEqual(saved.updatedAt, project.updatedAt);
  assert.equal(saved.scenes[0].layers.filter(item => item.id !== layer.id).map(item => item.asset).join('|'), scene.layers.filter(item => item.id !== layer.id).map(item => item.asset).join('|'));
  const other = await store.create('news-article', { title: 'Other story' });
  const reloaded = await store.get(other.id);
  assert.equal(reloaded.updatedAt, other.updatedAt);
});
